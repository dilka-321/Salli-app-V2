/* Copies the sign-in library and the app fonts into www/vendor so Salli works fully offline
   (Android APK and website). Runs automatically in the GitHub workflows after `npm install`.
   Safe to run again; if something is missing the app falls back to the internet copies. */
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), out = path.join(root, 'www', 'vendor');
fs.mkdirSync(path.join(out, 'fonts'), { recursive: true });
const nm = p => path.join(root, 'node_modules', p);

// 1) Supabase sign-in library (UMD build exposes window.supabase)
const sbDir = nm('@supabase/supabase-js/dist/umd');
const sbFile = fs.existsSync(sbDir) && fs.readdirSync(sbDir).find(f => /^supabase(\.min)?\.js$/.test(f));
if (sbFile) { fs.copyFileSync(path.join(sbDir, sbFile), path.join(out, 'supabase.js')); console.log('vendor: supabase.js'); }
else console.warn('vendor: @supabase/supabase-js UMD build not found — the app will load it from the internet');

// 2) Fonts used by Settings › Font (only .woff2 files are copied)
const FONTS = {
  'inter': [400, 500, 600, 700, 800], 'poppins': [400, 500, 600, 700, 800], 'manrope': [400, 500, 600, 700, 800],
  'dm-sans': [400, 500, 600, 700, 800], 'nunito': [400, 500, 600, 700, 800], 'roboto': [400, 500, 700, 900],
  'lora': [400, 500, 600, 700], 'noto-sans-sinhala': [400, 600], 'noto-sans-tamil': [400, 600]
};
let css = '/* generated by scripts/copy-vendor.js */\n';
for (const [name, weights] of Object.entries(FONTS)) {
  const dir = nm('@fontsource/' + name);
  if (!fs.existsSync(dir)) { console.warn('vendor: font missing', name); continue; }
  const dest = path.join(out, 'fonts', name); fs.mkdirSync(path.join(dest, 'files'), { recursive: true });
  for (const w of weights) {
    const f = path.join(dir, w + '.css'); if (!fs.existsSync(f)) continue;
    let c = fs.readFileSync(f, 'utf8');
    c = c.replace(/,\s*url\([^)]*\.woff\)\s*format\(['"]woff['"]\)/g, '');            // keep woff2 only
    c = c.replace(/url\(\.\/files\//g, 'url(./' + name + '/files/');
    css += c + '\n';
    for (const m of c.matchAll(/files\/([^)'"]+\.woff2)/g)) {
      const src = path.join(dir, 'files', m[1]); if (fs.existsSync(src)) fs.copyFileSync(src, path.join(dest, 'files', m[1]));
    }
  }
  console.log('vendor: font', name);
}
fs.writeFileSync(path.join(out, 'fonts', 'fonts.css'), css);
